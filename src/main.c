 #include <stm32f401xe.h>
int main(){
    /*  U = UNSIGNED INT (E' OTTIMA CONVENZIONE USARLO)
        QUINDI SUCCEDE CHE VIENE ACCESO IL PRIMO BIT DI AHB1ENR (GPIOA)
        VEDERE RM (ref. manual) del stm32f401ce
        IN PRATICA SUCCEDE QUESTO, EFFETTUA SHIFT DEL BIT 1 (01) DI 0    
        00000000 00000000 00000000 00000000
        OR
        00000000 00000000 00000000 00000001
    */
    RCC->AHB1ENR |= (1U<<0);
    
    /*  3U PERCHE' 011 << 2 RISULTA: 011 << 2 = 01100 (DOBBIAMO IMPOSTARE BIT 3 e 2)
        00000000 00000000 00000000 00000000              
        AND  
    NOT(00000000 00000000 00000000 00001100)
        STIAMO PRIMA SPEGNENDO MODER PER NON AVERE BIT ACCESI AI RIAVVII.                                 
    */
    GPIOA->MODER &= ~(3U << 2);

    /* INFINE ACCENDIAMO IL BIT 2 (SEMPRE RIFERIRSI AL MANUALE) */
    GPIOA->MODER |= (1U<<2);
    
    while (1){
        /* UTILIZZIAMO LO XOR, SE 1 ALLORA 0, SE 0 ALLORA 1 */
        GPIOA->ODR ^= (1U<<1);
        /*  TIMER PER FAR LAMPEGGIARE OGNI SECONDO CIRCA, VOLATILE SERVE
            AL COMPILATORE PER NON RIMUOVERE QUESTO LOOP CHE NON COMBINA NULLA */
        for (volatile int i = 0; i < 1000000; i++);
    }
}